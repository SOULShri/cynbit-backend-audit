/**
 * @file database-example.ts
 * @description PostgreSQL data access layer using Prisma ORM and Repository Pattern.
 *
 * ── What changed from v1 ─────────────────────────────────────────────────────
 * • Email is NOT unique on Inquiry — a customer may submit multiple inquiries
 *   (the previous schema had @@index([email]) which is fine for queries, but
 *   the unique constraint has been explicitly removed and documented).
 * • `any` types replaced with explicit Prisma-shaped interfaces.
 * • Cache invalidation added after status updates (updateStatus method).
 * • Redis cache failure is documented; the repository falls back to the DB.
 * • Connection pooling is documented; operators must use PgBouncer or Prisma
 *   Accelerate in serverless environments.
 * • mapToDTO is a static method to avoid 'this' binding issues in array.map().
 * ──────────────────────────────────────────────────────────────────────────────
 *
 * NOTE — This is a recommended reference implementation.
 * It is NOT Cynbit's actual source code.
 */

import type { CreateInquiryDTO, InquiryQueryDTO, InquiryResponseDTO } from './validation-example';

// ──────────────────────────────────────────────────────────────────────────────
// Prisma schema reference (what schema.prisma should contain)
// ──────────────────────────────────────────────────────────────────────────────
export const PrismaSchemaReference = `
datasource db {
  provider = "postgresql"
  url      = env("DATABASE_URL")
  // In serverless environments, enable connection pooling via PgBouncer:
  //   directUrl = env("DIRECT_URL")      // bypasses PgBouncer for migrations
  //   url       = env("POOLED_URL")      // PgBouncer / Prisma Accelerate URL
}

generator client {
  provider = "prisma-client-js"
}

enum Industry {
  AI_AUTOMATION
  ENTERPRISE_SOFTWARE
  CLOUD_INFRASTRUCTURE
  EDTECH_TRAINING
  REAL_ESTATE_SAAS
  OTHER
}

enum InquiryStatus {
  PENDING
  REVIEWED
  CONTACTED
  ARCHIVED
}

model Inquiry {
  id        String        @id @default(uuid())
  fullName  String        @map("full_name") @db.VarChar(100)
  // NOT unique — the same customer may submit multiple separate inquiries.
  email     String        @db.VarChar(254)
  company   String        @default("Independent / Undisclosed") @db.VarChar(120)
  industry  Industry      @default(OTHER)
  message   String        @db.Text
  status    InquiryStatus @default(PENDING)
  clientIp  String?       @map("client_ip") @db.VarChar(45)
  createdAt DateTime      @default(now()) @map("created_at")
  updatedAt DateTime      @updatedAt @map("updated_at")

  // Composite index for the most common admin query: filter by status, sorted by date.
  @@index([status, createdAt(sort: Desc)])
  // Index for searching by email (not unique — lookup only).
  @@index([email])
  @@index([industry])
  @@map("inquiries")
}
`;

// ──────────────────────────────────────────────────────────────────────────────
// Typed interfaces replacing `any`
// These match the shape generated by Prisma based on the schema above.
// ──────────────────────────────────────────────────────────────────────────────

export type InquiryIndustry =
  | 'AI_AUTOMATION'
  | 'ENTERPRISE_SOFTWARE'
  | 'CLOUD_INFRASTRUCTURE'
  | 'EDTECH_TRAINING'
  | 'REAL_ESTATE_SAAS'
  | 'OTHER';

export type InquiryStatus =
  | 'PENDING'
  | 'REVIEWED'
  | 'CONTACTED'
  | 'ARCHIVED';

/** Represents a row from the inquiries table. */
export interface InquiryRecord {
  id: string;
  fullName: string;
  email: string;
  company: string;
  industry: InquiryIndustry;
  message: string;
  status: InquiryStatus;
  clientIp: string | null;
  createdAt: Date;
  updatedAt: Date;
}

/** Prisma WHERE clause for Inquiry queries. */
export interface InquiryWhereInput {
  industry?: InquiryIndustry;
  status?: InquiryStatus;
  OR?: Array<{
    fullName?: { contains: string; mode: 'insensitive' };
    company?: { contains: string; mode: 'insensitive' };
    email?: { contains: string; mode: 'insensitive' };
  }>;
}

/**
 * Typed Prisma client interface — replaces `any`.
 * Matches the auto-generated @prisma/client API surface for the Inquiry model.
 */
export interface PrismaInquiryClient {
  inquiry: {
    create(args: {
      data: Omit<InquiryRecord, 'id' | 'createdAt' | 'updatedAt'>;
    }): Promise<InquiryRecord>;

    findUnique(args: {
      where: { id: string };
    }): Promise<InquiryRecord | null>;

    findMany(args: {
      where?: InquiryWhereInput;
      skip?: number;
      take?: number;
      orderBy?: Partial<Record<keyof InquiryRecord, 'asc' | 'desc'>>;
    }): Promise<InquiryRecord[]>;

    count(args: { where?: InquiryWhereInput }): Promise<number>;

    update(args: {
      where: { id: string };
      data: Partial<Pick<InquiryRecord, 'status' | 'fullName' | 'company' | 'industry' | 'message'>>;
    }): Promise<InquiryRecord>;
  };

  $transaction<T>(fn: (tx: PrismaInquiryClient) => Promise<T>): Promise<T>;
}

/**
 * Unified Redis cache interface for repository read-through caching.
 *
 * NOTE ON CLIENT DIFFERENCES:
 * `ioredis` implements `.setex(key, seconds, value)`.
 * `node-redis` (v4+) implements `.setEx(key, seconds, value)` or `.set(key, value, { EX: seconds })`.
 * Cross-client compatibility cannot be assumed without explicit adapters.
 * Use `createIoRedisCacheAdapter` or `createNodeRedisCacheAdapter` to bridge client APIs.
 */
export interface RedisCacheAdapter {
  get(key: string): Promise<string | null>;
  set(key: string, value: string, ttlSeconds: number): Promise<unknown>;
  del(key: string): Promise<unknown>;
}

/** Legacy / raw client interface supported with adapter normalization. */
export interface RedisClientLike {
  get(key: string): Promise<string | null>;
  setEx?(key: string, ttlSeconds: number, value: string): Promise<unknown>;
  setex?(key: string, ttlSeconds: number, value: string): Promise<unknown>;
  set?(key: string, value: string, options?: { EX?: number }): Promise<unknown>;
  del(key: string): Promise<unknown>;
}

export type RedisCacheOption = RedisCacheAdapter | RedisClientLike;

/**
 * Creates a cache adapter for `ioredis` clients.
 * Translates standard `.set(key, value, ttl)` to ioredis `.setex(key, ttl, value)`.
 */
export function createIoRedisCacheAdapter(ioredisClient: {
  get(key: string): Promise<string | null>;
  setex(key: string, seconds: number, value: string): Promise<unknown>;
  del(key: string): Promise<unknown>;
}): RedisCacheAdapter {
  return {
    get: (key: string) => ioredisClient.get(key),
    set: (key: string, value: string, ttlSeconds: number) =>
      ioredisClient.setex(key, ttlSeconds, value),
    del: (key: string) => ioredisClient.del(key),
  };
}

/**
 * Creates a cache adapter for `node-redis` (v4+) clients.
 * Translates standard `.set(key, value, ttl)` to node-redis `.setEx(key, ttl, value)` or `.set(key, value, { EX: ttl })`.
 */
export function createNodeRedisCacheAdapter(nodeRedisClient: {
  get(key: string): Promise<string | null>;
  setEx?(key: string, seconds: number, value: string): Promise<unknown>;
  set?(key: string, value: string, options?: { EX?: number }): Promise<unknown>;
  del(key: string): Promise<unknown>;
}): RedisCacheAdapter {
  return {
    get: (key: string) => nodeRedisClient.get(key),
    set: async (key: string, value: string, ttlSeconds: number) => {
      if (typeof nodeRedisClient.setEx === 'function') {
        return nodeRedisClient.setEx(key, ttlSeconds, value);
      }
      if (typeof nodeRedisClient.set === 'function') {
        return nodeRedisClient.set(key, value, { EX: ttlSeconds });
      }
      throw new Error('node-redis client must implement setEx or set');
    },
    del: (key: string) => nodeRedisClient.del(key),
  };
}

/** Normalizes a raw Redis client or adapter into a consistent RedisCacheAdapter. */
function normalizeCacheClient(client?: RedisCacheOption): RedisCacheAdapter | undefined {
  if (!client) return undefined;
  if ('set' in client && typeof client.set === 'function' && client.set.length >= 3) {
    return client as RedisCacheAdapter;
  }
  return {
    get: (key: string) => client.get(key),
    set: async (key: string, value: string, ttlSeconds: number) => {
      if ('setEx' in client && typeof client.setEx === 'function') {
        return client.setEx(key, ttlSeconds, value);
      }
      if ('setex' in client && typeof client.setex === 'function') {
        return client.setex(key, ttlSeconds, value);
      }
      if ('set' in client && typeof client.set === 'function') {
        const setFn = client.set as (k: string, v: string, opt?: { EX?: number }) => Promise<unknown>;
        return setFn(key, value, { EX: ttlSeconds });
      }
      throw new Error('Unsupported Redis client interface. Provide an explicit adapter via createIoRedisCacheAdapter or createNodeRedisCacheAdapter.');
    },
    del: (key: string) => client.del(key),
  };
}

// ──────────────────────────────────────────────────────────────────────────────
// Repository
//
// Connection pooling note:
//   When deploying to a serverless environment (e.g. Vercel, AWS Lambda) each
//   function invocation opens a new database connection. Without pooling this
//   quickly exhausts PostgreSQL's max_connections. Use either:
//     - Prisma Accelerate (managed connection pool)
//     - PgBouncer (self-managed, transaction-mode pooling)
//   Configure the pooled DATABASE_URL in the datasource block.
//
// Redis cache failure policy:
//   A cache miss or Redis error is NEVER fatal. The repository always falls
//   back to the database. This means a Redis outage degrades performance
//   (more DB load) but does not cause availability loss.
// ──────────────────────────────────────────────────────────────────────────────
export class InquiryRepository {
  private readonly redis?: RedisCacheAdapter;

  constructor(
    private readonly prisma: PrismaInquiryClient,
    redis?: RedisCacheOption
  ) {
    this.redis = normalizeCacheClient(redis);
  }

  // ── Create ─────────────────────────────────────────────────────────────────

  public async create(dto: CreateInquiryDTO, clientIp: string): Promise<InquiryResponseDTO> {
    const record = await this.prisma.inquiry.create({
      data: {
        fullName: dto.fullName,
        email: dto.email,
        company: dto.company ?? 'Independent / Undisclosed',
        industry: dto.industry as InquiryIndustry,
        message: dto.message,
        status: 'PENDING',
        clientIp,
      },
    });
    return InquiryRepository.mapToDTO(record);
  }

  // ── List with pagination ────────────────────────────────────────────────────

  public async findManyWithPagination(query: InquiryQueryDTO): Promise<{
    items: InquiryResponseDTO[];
    total: number;
    page: number;
    limit: number;
  }> {
    const { page, limit, industry, status, search, sortBy, sortOrder } = query;
    const skip = (page - 1) * limit;

    const where: InquiryWhereInput = {};

    if (industry) {
      where.industry = industry as InquiryIndustry;
    }
    if (status) {
      where.status = status as InquiryStatus;
    }
    if (search) {
      where.OR = [
        { fullName: { contains: search, mode: 'insensitive' } },
        { company: { contains: search, mode: 'insensitive' } },
        { email: { contains: search, mode: 'insensitive' } },
      ];
    }

    // Use a transaction to keep the count consistent with the returned page.
    const [records, total] = await this.prisma.$transaction(async (tx) => {
      const items = await tx.inquiry.findMany({
        where,
        skip,
        take: limit,
        orderBy: { [sortBy]: sortOrder },
      });
      const count = await tx.inquiry.count({ where });
      return [items, count] as [InquiryRecord[], number];
    });

    return {
      items: records.map(InquiryRepository.mapToDTO),
      total,
      page,
      limit,
    };
  }

  // ── Find by ID (with read-through cache) ───────────────────────────────────

  public async findById(id: string): Promise<InquiryResponseDTO | null> {
    const cacheKey = `cynbit:inquiry:${id}`;

    if (this.redis) {
      try {
        const cached = await this.redis.get(cacheKey);
        if (cached) {
          return JSON.parse(cached) as InquiryResponseDTO;
        }
      } catch {
        // Cache read failure — fall through to database. (see cache failure policy above)
      }
    }

    const record = await this.prisma.inquiry.findUnique({ where: { id } });
    if (!record) return null;

    const dto = InquiryRepository.mapToDTO(record);

    if (this.redis) {
      // Cache for 10 minutes. Swallow errors — a write failure is not critical.
      await this.redis.set(cacheKey, JSON.stringify(dto), 600).catch(() => undefined);
    }

    return dto;
  }

  // ── Update status (with cache invalidation) ─────────────────────────────────

  /**
   * Updates the status of an inquiry record.
   * Invalidates the cache entry for this record so stale data is not served.
   *
   * Cache invalidation strategy:
   *   - On a successful update, the cached item is deleted.
   *   - The next findById call will re-populate the cache from the DB.
   *   - If the cache delete fails, the stale entry will expire naturally (10-min TTL).
   */
  public async updateStatus(id: string, status: InquiryStatus): Promise<InquiryResponseDTO> {
    const record = await this.prisma.inquiry.update({
      where: { id },
      data: { status },
    });

    // Invalidate after the write succeeds.
    if (this.redis) {
      const cacheKey = `cynbit:inquiry:${id}`;
      await this.redis.del(cacheKey).catch(() => undefined);
    }

    return InquiryRepository.mapToDTO(record);
  }

  // ── Mapping ─────────────────────────────────────────────────────────────────

  /** Pure static mapper — avoids 'this' binding issues in array.map(). */
  private static mapToDTO(record: InquiryRecord): InquiryResponseDTO {
    return {
      id: record.id,
      fullName: record.fullName,
      email: record.email,
      company: record.company,
      industry: record.industry,
      message: record.message,
      status: record.status,
      createdAt: record.createdAt,
      updatedAt: record.updatedAt,
    };
  }
}
